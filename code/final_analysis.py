"""
MGT-403 Data Project - Final Project Analysis: Where should we locate our childcare centers?
===========================================================================================
Method
  1. For each year 2015-2022, regress the median weekly center-based preschool price (2022 $) on
     childcare-worker wage ($1,000s), median gross rent ($100s) and female college share (pct. points)
     across metro counties -> predicted price for every county-year.
     (Main model chosen by the team: wage + rent + female college share. The cost-only model
      wage + rent is reported as a robustness check.)
  2. Residual = actual price - predicted price ($/week). A large positive residual = a county that
     charges more than its costs (and education level) would predict -> attractive market.
  3. Recommend the 10 counties with the largest 2022 residuals (no one-per-metro limit; repeated
     metros are flagged and the next 5 alternates listed).
  4. Stability: compare 2019 vs 2022 residuals (pre- vs post-Covid) and track the top 10 across
     all years 2015-2022.

Run order:  python3 code/pre_analysis.py   (builds data/processed/analysis_dataset.csv)
            python3 code/final_analysis.py
Requires pandas, numpy, matplotlib. OLS / HC1 helpers are imported from pre_analysis.py.

Outputs (all regenerated by this script):
  output/tables/final_residuals_all_years.csv    every county-year: predicted price, residual, ranks
  output/tables/final_models_by_year.{csv,md}    yearly regression coefficients (HC1 SEs), R2
  output/tables/final_top10_2022.{csv,md}        recommended counties + alternates 11-15
  output/tables/final_robustness_cost_only.{csv,md}
  output/tables/final_stability_2019_2022.{csv,md}
  output/figures/final_top10_residuals_2022.png
  output/figures/final_residual_2019_vs_2022.png
  output/figures/final_top10_residuals_by_year.png
  output/final_analysis_writeup.md
  output/final_analysis_log.txt
"""
