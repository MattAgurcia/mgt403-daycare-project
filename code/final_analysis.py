# ------------------------------------------------------------------ step 1-2: yearly fits
def fit_all_years(cols, tag):
    parts, models = [], []
    for y in YEARS:
        a = A[A["year"] == y].copy()
        X = np.column_stack([np.ones(len(a))] + [a[c].to_numpy() for c in cols])
        m = ols(a["y"].to_numpy(), X, ["Intercept"] + cols)
        a["pred"] = m["fitted"]
        a["resid"] = m["resid"]
        a["resid_pct"] = 100 * a["resid"] / a["pred"]
        a["rank"] = a["resid"].rank(ascending=False, method="first").astype(int)
        a["pctile"] = 100 * a["resid"].rank(pct=True)
        a["quintile"] = pd.qcut(a["resid"].rank(method="first"), 5, labels=[1, 2, 3, 4, 5]).astype(int)
        parts.append(a)
        row = {"model": tag, "year": y, "N": m["n"], "R2": m["r2"], "adj_R2": m["adj_r2"],
               "resid_sd": a["resid"].std()}
        for i, nm in enumerate(m["names"]):
            row[nm] = m["b"][i]; row[nm + "_se"] = m["se"][i]; row[nm + "_p"] = m["p"][i]
        row["n_imputed_rows"] = int(a["imputed_any"].sum())
        models.append(row)
    return pd.concat(parts, ignore_index=True), pd.DataFrame(models)


