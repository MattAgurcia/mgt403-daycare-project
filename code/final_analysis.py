def straight_line_fill(df, col):
    """Fill interior gaps of <= MAX_GAP consecutive years by linear interpolation between the
    nearest observed years before and after (the method NDCP uses for years between surveys).
    Only county-years that are in the metro panel are filled; endpoints are never extrapolated."""
    wide = df.pivot(index="county_fips", columns="year", values=col).reindex(columns=YEARS)
    present = df.assign(_p=1).pivot(index="county_fips", columns="year", values="_p").reindex(columns=YEARS).notna()
    filled, flag = wide.copy(), pd.DataFrame(False, index=wide.index, columns=wide.columns)
    vals, pres = wide.to_numpy(), present.to_numpy()
    for i in range(vals.shape[0]):
        j = 0
        while j < len(YEARS):
            if pres[i, j] and np.isnan(vals[i, j]):
                k = j
                while k + 1 < len(YEARS) and pres[i, k + 1] and np.isnan(vals[i, k + 1]):
                    k += 1
                lo, hi = j - 1, k + 1                          # neighbours just outside the run
                if (k - j + 1) <= MAX_GAP and lo >= 0 and hi < len(YEARS) and pres[i, lo] and pres[i, hi] \
                        and not np.isnan(vals[i, lo]) and not np.isnan(vals[i, hi]):
                    for t in range(j, k + 1):
                        w = (t - lo) / (hi - lo)
                        filled.iat[i, t] = vals[i, lo] + w * (vals[i, hi] - vals[i, lo])
                        flag.iat[i, t] = True
                j = k + 1
            else:
                j += 1
    long_v = filled.stack().rename(col).reset_index()
    long_f = flag.stack().rename("imp_" + col).reset_index()
    return long_v.merge(long_f, on=["county_fips", "year"], how="right")


